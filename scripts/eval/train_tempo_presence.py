#!/usr/bin/env python3
"""Train the "does this sound have a tempo?" gate (loops vs long one-shots).

    python scripts/eval/train_tempo_presence.py <presence.jsonl> --names tempo-names.json [--export src/shared/tempoPresenceModel.ts]

Input rows come from an eval run whose entry returns the tempo estimator's global
descriptors and best-candidate features (one-shots ≥ 1.2 s and labelled loops).
Logistic regression on standardised features; folds grouped by sample pack.
"""
import json
import sys
import numpy as np
from sklearn.linear_model import LogisticRegression

GLOBAL = ['logDur', 'logOnsetRate', 'rhythmic', 'highShare', 'lowShare', 'logCentroid', 'lowEnergy', 'flatness',
          'salMax', 'mfcc1', 'mfcc2', 'mfcc3', 'mfcc4', 'mfcc5', 'mfcc6']
PICK = ['lsal', 'intClose', 'intMid', 'sPow2', 'sAudio', 'combPeak', 'phase0', 'onsetsPerBeat', 'mBeat', 'm8th',
        'm16th', 'r1', 'r2', 'r4']


def main():
    rows = [json.loads(l) for l in open(sys.argv[1])]
    rows = [r for r in rows if not r.get('error') and r.get('pred') and r['pred'].get('global')]
    base = json.load(open(sys.argv[sys.argv.index('--names') + 1]))
    idx = [base.index(p) for p in PICK]
    X, y, packs = [], [], []
    for r in rows:
        p = r['pred']
        X.append(list(p['global']) + [p['bpmConfidence'], 1.0 if p['method'] == 'loop-grid' else 0.0] + [p['best'][i] for i in idx])
        y.append(1 if r['kind'] == 'loop' else 0)
        packs.append(r.get('pack') or r['path'])
    X, y = np.array(X), np.array(y)
    names = GLOBAL + ['pBest', 'isGrid'] + PICK
    up = sorted(set(packs))
    rng = np.random.default_rng(0)
    rng.shuffle(up)
    fo = {p: i % 5 for i, p in enumerate(up)}
    fold = np.array([fo[p] for p in packs])
    mu, sd = X.mean(0), X.std(0) + 1e-9
    Z = (X - mu) / sd
    P = np.zeros(len(y))
    for f in range(5):
        clf = LogisticRegression(C=0.5, max_iter=2000).fit(Z[fold != f], y[fold != f])
        P[fold == f] = clf.predict_proba(Z[fold == f])[:, 1]
    print(f'{int(y.sum())} loops, {int((1 - y).sum())} long one-shots')
    for thr in [0.3, 0.4, 0.5, 0.6]:
        tp = ((P >= thr) & (y == 1)).sum()
        fp = ((P >= thr) & (y == 0)).sum()
        print(f'  threshold {thr}: loop recall {tp / y.sum():.3f}, one-shot false tempo {fp / (1 - y).sum():.3f}')
    clf = LogisticRegression(C=0.5, max_iter=2000).fit(Z, y)
    w = clf.coef_[0] / sd
    b = clf.intercept_[0] - float((clf.coef_[0] * mu / sd).sum())
    if '--export' in sys.argv:
        path = sys.argv[sys.argv.index('--export') + 1]
        lines = '\n'.join(f'    {v:.6f}, // {n}' for n, v in zip(names, w))
        open(path, 'w').write(
            '// Generated by scripts/eval/train_tempo_presence.py — do not edit by hand.\n'
            '// Logistic gate: P(sound has a musical tempo) from the tempo estimator\'s evidence.\n'
            f'// Trained on {int(y.sum())} loops vs {int((1 - y).sum())} one-shots ≥ 1.2 s (pack-grouped CV above).\n'
            'export const TEMPO_PRESENCE_MODEL = {\n'
            f'  bias: {b:.6f},\n'
            f'  globalNames: {json.dumps(GLOBAL)},\n'
            f'  candidateNames: {json.dumps(PICK)},\n'
            '  // order: globalNames, pBest, isGrid, candidateNames\n'
            '  weights: [\n' + lines + '\n  ]\n}\n'
        )
        print('model →', path)


if __name__ == '__main__':
    main()
